// ---------------------------------------------------------------------------
// Cross-Border Transfer Logging
// ---------------------------------------------------------------------------

export async function logCrossBorderTransfer(params: {
  organizationId: number;
  userId: number | string;
  transferType: "ai_inference" | "email_delivery" | "file_storage" | "voice_transcription";
  sourceRegion: DataResidencyRegion;
  destinationRegion: string;
  dataCategories: string[];
  consentObtained: boolean;
}): Promise<void> {
  const db = await getDb();
  if (!db) return;
  await db.insert(auditLog).values({
    organizationId: params.organizationId,
    userId: typeof params.userId === "string" ? parseInt(params.userId, 10) || 0 : params.userId,
    action: "cross_border_transfer",
    entityType: "compliance",
    entityId: "0",
    details: JSON.stringify({
      transferType: params.transferType,
      sourceRegion: params.sourceRegion,
      destinationRegion: params.destinationRegion,
      dataCategories: params.dataCategories,
      consentObtained: params.consentObtained,
      flag: "[CROSS-BORDER TRANSFER]",
      timestamp: new Date().toISOString(),
    }),
    createdAt: new Date(),
  });
}

// ---------------------------------------------------------------------------
// Tenant Compliance Config Helpers
// ---------------------------------------------------------------------------

export interface TenantComplianceConfig {
  dataResidency: DataResidencyRegion;
  complianceMode: ComplianceMode;
  featureFlags: TenantFeatureFlags;
  crossBorderConsentGiven: boolean;
  crossBorderConsentDate: Date | null;
}

export const DEFAULT_COMPLIANCE_CONFIG: TenantComplianceConfig = {
  dataResidency: "us",
  complianceMode: "technology_vendor_only",
  featureFlags: DEFAULT_FEATURE_FLAGS,
  crossBorderConsentGiven: false,
  crossBorderConsentDate: null,
};

/**
 * Get the compliance configuration for a tenant.
 * Falls back to defaults if not configured.
 */
export async function getTenantComplianceConfig(
  organizationId: number
): Promise<TenantComplianceConfig> {
  const db = await getDb();
  if (!db) return DEFAULT_COMPLIANCE_CONFIG;
  const [org] = await db
    .select()
    .from(organizations)
    .where(eq(organizations.id, organizationId))
    .limit(1);

  if (!org) return DEFAULT_COMPLIANCE_CONFIG;

  // Parse compliance config from org metadata if stored
  const metadata = (org as any).complianceConfig;
  if (!metadata) return DEFAULT_COMPLIANCE_CONFIG;

  try {
    const parsed = typeof metadata === "string" ? JSON.parse(metadata) : metadata;
    return {
      dataResidency: parsed.dataResidency || "us",
      complianceMode: parsed.complianceMode || "technology_vendor_only",
      featureFlags: { ...DEFAULT_FEATURE_FLAGS, ...(parsed.featureFlags || {}) },
      crossBorderConsentGiven: parsed.crossBorderConsentGiven || false,
      crossBorderConsentDate: parsed.crossBorderConsentDate
        ? new Date(parsed.crossBorderConsentDate)
        : null,
    };
  } catch {
    return DEFAULT_COMPLIANCE_CONFIG;
  }
}

/**
 * Check if a feature is enabled for a tenant.
 * Returns false for disabled features, preventing execution.
 */
export function isFeatureEnabled(
  config: TenantComplianceConfig,
  feature: keyof TenantFeatureFlags
): boolean {
  return config.featureFlags[feature] ?? false;
}

/**
 * Get the appropriate AI output label based on compliance mode.
 */
export function getAIOutputLabel(config: TenantComplianceConfig): string {
  return COMPLIANCE_LABELS[config.complianceMode].aiOutputLabel;
}

/**
 * Get the appropriate disclaimer prefix based on compliance mode.
 */
export function getDisclaimerPrefix(config: TenantComplianceConfig): string {
  return COMPLIANCE_LABELS[config.complianceMode].disclaimerPrefix;
}

/**
 * Check if a cross-border transfer requires consent and whether it has been given.
 */
export async function checkCrossBorderConsent(
  organizationId: number,
  transferType: string
): Promise<{ required: boolean; consented: boolean }> {
  const config = await getTenantComplianceConfig(organizationId);
  const regionConfig = REGION_CONFIG[config.dataResidency];

  if (!regionConfig.crossBorderRequired) {
    return { required: false, consented: true };
  }

  return {
    required: true,
    consented: config.crossBorderConsentGiven,
  };
}
