// ─── Constants ────────────────────────────────────────────────────────────

/** Default confidence threshold below which human review is mandatory */
export const DEFAULT_CONFIDENCE_THRESHOLD = 70;

/** Agent-specific confidence thresholds (overridable per client config) */
export const AGENT_CONFIDENCE_THRESHOLDS: Record<string, number> = {
  "Overdue Agent": 70,
  "Velocity Agent": 60,
  "Distribution Sentinel": 80,  // higher bar for financial communications
  "Orchestrator": 70,
};

/**
 * Standard disclaimer for AI-generated client-facing content.
 * WS9: Uses ComplianceMode label when available.
 * In technology_vendor_only mode: "Operational Suggestion"
 * In advisory_enabled mode: "Recommendation" (requires legal clearance)
 */
export function generateDisclaimer(
  operatorName?: string,
  date?: Date,
  complianceMode?: "technology_vendor_only" | "advisory_enabled"
): string {
  const d = date || new Date();
  const dateStr = d.toISOString().split("T")[0];
  const reviewer = operatorName || "[Pending Review]";
  const mode = complianceMode || "technology_vendor_only";
  const label = mode === "advisory_enabled" ? "Recommendation" : "Operational Suggestion";
  const prefix = mode === "advisory_enabled"
    ? "This recommendation was generated by AI. Consult qualified advisors before acting."
    : "This is an operational suggestion generated by VENTEX AI agents. Not investment, legal, or tax advice.";
  return `AI-assisted output reviewed by ${reviewer} on ${dateStr}. ${prefix} All decisions should be independently verified.`;
}

/** Disclaimer for internal/operator-facing content */
export function generateOperatorDisclaimer(): string {
  return `AI-generated analysis. Confidence scores reflect model certainty, not factual accuracy. Verify critical data points independently before acting.`;
}

// ─── Confidence Scoring ──────────────────────────────────────────────────

/**
 * Compute a confidence score for an agent output based on:
 * - Data completeness (are all expected fields present?)
 * - Agent type (some agents have inherently higher/lower confidence)
 * - Context quality (how much data was available to the agent?)
 */
export function computeConfidenceScore(params: {
  agentName: string;
  hasEntityData: boolean;
  hasHistoricalData: boolean;
  hasBlueprintContext: boolean;
  outputQuality?: "high" | "medium" | "low";
}): number {
  let score = 50; // base score

  // Data completeness bonuses
  if (params.hasEntityData) score += 15;
  if (params.hasHistoricalData) score += 15;
  if (params.hasBlueprintContext) score += 10;

  // Output quality adjustment
  if (params.outputQuality === "high") score += 10;
  else if (params.outputQuality === "low") score -= 15;

  // Agent-specific adjustments
  if (params.agentName === "Distribution Sentinel") score -= 5; // financial = more cautious
  if (params.agentName === "Orchestrator") score += 5; // aggregation = more reliable

  return Math.max(0, Math.min(100, score));
}

// ─── Approval Enforcement ────────────────────────────────────────────────

/**
 * Determine if an action requires human approval based on:
 * - Action type (drafts, stage advances, financial comms always require approval)
 * - Confidence score vs threshold
 * - Client-facing vs operator-only
 */
export function requiresHumanApproval(params: {
  actionType?: string | null;
  audience?: string;
  confidenceScore?: number;
  agentName?: string;
  isFinancial?: boolean;
}): boolean {
  // All client-facing communications require approval
  if (params.audience === "client" || params.audience === "both") return true;

  // All draft communications require approval
  if (params.actionType === "draft") return true;

  // All stage advances require approval
  if (params.actionType === "advance") return true;

  // All financial-related actions require approval
  if (params.isFinancial) return true;

  // Low confidence outputs require approval
  const threshold = params.agentName
    ? AGENT_CONFIDENCE_THRESHOLDS[params.agentName] || DEFAULT_CONFIDENCE_THRESHOLD
    : DEFAULT_CONFIDENCE_THRESHOLD;
  if (params.confidenceScore !== undefined && params.confidenceScore < threshold) return true;

  // Default: require approval (fail-safe)
  return true;
}

/**
 * Check if an event/draft has been approved before allowing execution.
 * Returns true if approved or if approval is not required.
 */
export function isApprovedForExecution(params: {
  humanApprovalRequired: boolean;
  approvalStatus?: string | null;
}): boolean {
  if (!params.humanApprovalRequired) return true;
  return params.approvalStatus === "approved";
}

// ─── Approval Logging ────────────────────────────────────────────────────

/**
 * Log an approval/rejection action to the immutable audit trail
 */
export async function logApprovalAction(params: {
  entityType: "event" | "draft";
  entityId: number;
  action: "approved" | "rejected" | "edited";
  actorId?: number;
  actorName: string;
  originalContent?: string;
  finalContent?: string;
  reason?: string;
  confidenceScore?: number;
  disclaimerApplied?: string;
}): Promise<void> {
  const db = await getDb();
  if (!db) return;

  await db.insert(agentApprovalLog).values({
    entityType: params.entityType,
    entityId: params.entityId,
    action: params.action,
    actorId: params.actorId ?? null,
    actorName: params.actorName,
    originalContent: params.originalContent ?? null,
    finalContent: params.finalContent ?? null,
    reason: params.reason ?? null,
    confidenceScore: params.confidenceScore ?? null,
    disclaimerApplied: params.disclaimerApplied ?? null,
  });
}

// ─── Draft Safety Helpers ────────────────────────────────────────────────

/**
 * Attach safety metadata to a draft before insertion.
 * Returns the extra fields to merge into the insert values.
 */
export function getDraftSafetyFields(params: {
  agentName: string;
  draftType: string;
  hasEntityData: boolean;
  hasHistoricalData?: boolean;
  hasBlueprintContext?: boolean;
}): {
  humanApprovalRequired: boolean;
  approvalStatus: string;
  confidenceScore: number;
  disclaimer: string;
} {
  const confidenceScore = computeConfidenceScore({
    agentName: params.agentName,
    hasEntityData: params.hasEntityData,
    hasHistoricalData: params.hasHistoricalData ?? false,
    hasBlueprintContext: params.hasBlueprintContext ?? false,
  });

  const isFinancial = params.draftType === "lp_notice" || params.draftType === "distribution";

  return {
    humanApprovalRequired: true, // All drafts require approval
    approvalStatus: "pending",
    confidenceScore,
    disclaimer: generateDisclaimer(),
  };
}

/**
 * Attach safety metadata to an agent event before insertion.
 */
export function getEventSafetyFields(params: {
  agentName: string;
  actionType?: string | null;
  audience?: string;
  hasEntityData: boolean;
  hasHistoricalData?: boolean;
  hasBlueprintContext?: boolean;
  isFinancial?: boolean;
}): {
  humanApprovalRequired: boolean;
  approvalStatus: string;
  confidenceScore: number;
  disclaimer: string | null;
} {
  const confidenceScore = computeConfidenceScore({
    agentName: params.agentName,
    hasEntityData: params.hasEntityData,
    hasHistoricalData: params.hasHistoricalData ?? false,
    hasBlueprintContext: params.hasBlueprintContext ?? false,
  });

  const needsApproval = requiresHumanApproval({
    actionType: params.actionType,
    audience: params.audience,
    confidenceScore,
    agentName: params.agentName,
    isFinancial: params.isFinancial,
  });

  // Only client-facing events get disclaimers
  const disclaimer = (params.audience === "client" || params.audience === "both")
    ? generateDisclaimer()
    : null;

  return {
    humanApprovalRequired: needsApproval,
    approvalStatus: needsApproval ? "pending" : "approved",
    confidenceScore,
    disclaimer,
  };
}
